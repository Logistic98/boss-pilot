import Foundation

enum BossCityResolver {
    static func code(for value: String) -> String? {
        let trimmed = value.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return nil }
        if isLocationCode(trimmed) { return trimmed }
        for candidate in cityNameCandidates(trimmed) {
            if let code = cityCodes[candidate] { return code }
        }
        return nil
    }

    static func name(forCode value: String) -> String? {
        cityNamesByCode[value.trimmingCharacters(in: .whitespacesAndNewlines)]
    }

    static func displayText(for value: String) -> String {
        let trimmed = value.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return "" }

        let components = trimmed
            .components(separatedBy: "·")
            .map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
            .filter { !$0.isEmpty }
        let localized = components.compactMap { component -> String? in
            if let name = name(forCode: component) { return name }
            if isLocationCode(component) { return nil }
            return component
        }
        if localized.isEmpty, components.contains(where: isLocationCode) {
            return "地点未标注"
        }
        var seen = Set<String>()
        return localized
            .filter { seen.insert($0).inserted }
            .joined(separator: " · ")
    }

    private static func cityNameCandidates(_ value: String) -> [String] {
        var candidates = [value]
        for suffix in ["市", "地区", "盟"] where value.hasSuffix(suffix) && value.count > suffix.count {
            candidates.append(String(value.dropLast(suffix.count)))
        }
        var seen = Set<String>()
        return candidates.filter { seen.insert($0).inserted }
    }

    private static func isLocationCode(_ value: String) -> Bool {
        value.count >= 6 && value.allSatisfy(\.isNumber)
    }

